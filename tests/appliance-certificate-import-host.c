static void test_accepts_a_matching_pair_and_name(void)
{
    struct appliance_certificate_import_result result;
    bool fingerprint_nonzero = false;
    size_t index;

    CHECK(appliance_certificate_import_validate(
              fixture_certificate, sizeof(fixture_certificate),
              fixture_key, sizeof(fixture_key), NULL, 0U, FIXTURE_NOW,
              "hfoc-appliance", 14U, fixture_rng, NULL, &result) ==
              APPLIANCE_CERTIFICATE_IMPORT_OK,
          "a matching EC P-256 pair with the appliance SAN is accepted");
    CHECK(result.version == APPLIANCE_CERTIFICATE_IMPORT_VERSION &&
              result.name_length == 14U &&
              strcmp(result.name, "hfoc-appliance") == 0,
          "the accepted result carries the name that matched");
    CHECK(result.not_before_epoch < FIXTURE_NOW &&
              result.not_after_epoch > FIXTURE_NOW,
          "the accepted result carries the validated window");
    for (index = 0U; index < sizeof(result.fingerprint); ++index) {
        if (result.fingerprint[index] != 0U) {
            fingerprint_nonzero = true;
        }
    }
    CHECK(fingerprint_nonzero,
          "the accepted result carries the DER fingerprint");
}


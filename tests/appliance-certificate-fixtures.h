/* The pair check blinds its EC multiplication; a deterministic stub is
 * enough for the proof.  ITEM-508 increment 2's trust proof includes this
 * header without needing the stub, so it is `static inline`: a consumer that
 * does not call it stays warning-free. */
static inline int fixture_rng(
    void *context,
    unsigned char *output,
    size_t length)
{
    size_t index;

    (void)context;
    for (index = 0U; index < length; ++index) {
        output[index] = (unsigned char)(0xA5U ^ (unsigned char)index);
    }
    return 0;
}


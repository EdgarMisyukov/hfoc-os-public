#ifndef HFOC_MBEDTLS_MANIFEST_H
#define HFOC_MBEDTLS_MANIFEST_H

#include <stdbool.h>
#include <stdint.h>

#define HFOC_MBEDTLS_MANIFEST_VERSION 1U
#define HFOC_MBEDTLS_MANIFEST_MAGIC UINT32_C(0x434F4648)

#define HFOC_MBEDTLS_MANIFEST_PURPOSE_TLS_HANDSHAKE 1U
#define HFOC_MBEDTLS_MANIFEST_ALGORITHM_ECDSA_P256_SHA256 1U

#define HFOC_MBEDTLS_MANIFEST_HEADER_BYTES 126U
#define HFOC_MBEDTLS_MANIFEST_HOSTNAME "hfoc.test"
#define HFOC_MBEDTLS_MANIFEST_HOSTNAME_LENGTH 9U
#define HFOC_MBEDTLS_MANIFEST_HOSTNAME_MAX 64U

#define HFOC_MBEDTLS_MANIFEST_CERTIFICATE_MIN 1U
#define HFOC_MBEDTLS_MANIFEST_CERTIFICATE_MAX 2048U
#define HFOC_MBEDTLS_MANIFEST_KEY_MIN 1U
#define HFOC_MBEDTLS_MANIFEST_KEY_MAX 1024U
#define HFOC_MBEDTLS_MANIFEST_MAX_TOTAL_BYTES 4096U

#define HFOC_MBEDTLS_MANIFEST_SHA256_LENGTH 32U
#define HFOC_MBEDTLS_MANIFEST_PUBLIC_KEY_MAX_BYTES 256U

struct hfoc_mbedtls_manifest {
    bool published;
    uint32_t version;
    uint32_t purpose_id;
    uint32_t algorithm_id;
    uint8_t hostname[HFOC_MBEDTLS_MANIFEST_HOSTNAME_MAX];
    uint32_t hostname_length;
    const uint8_t *certificate;
    uint32_t certificate_length;
    const uint8_t *key;
    uint32_t key_length;
    uint8_t certificate_digest[HFOC_MBEDTLS_MANIFEST_SHA256_LENGTH];
};

enum hfoc_mbedtls_manifest_status {
    HFOC_MBEDTLS_MANIFEST_OK = 0,
    HFOC_MBEDTLS_MANIFEST_NULL = 1,
    HFOC_MBEDTLS_MANIFEST_BAD_MAGIC = 2,
    HFOC_MBEDTLS_MANIFEST_BAD_VERSION = 3,
    HFOC_MBEDTLS_MANIFEST_BAD_ENTRY_COUNT = 4,
    HFOC_MBEDTLS_MANIFEST_BAD_PURPOSE = 5,
    HFOC_MBEDTLS_MANIFEST_BAD_ALGORITHM = 6,
    HFOC_MBEDTLS_MANIFEST_BAD_HOSTNAME_LENGTH = 7,
    HFOC_MBEDTLS_MANIFEST_BAD_HOSTNAME = 8,
    HFOC_MBEDTLS_MANIFEST_BAD_CERTIFICATE_LENGTH = 9,
    HFOC_MBEDTLS_MANIFEST_BAD_KEY_LENGTH = 10,
    HFOC_MBEDTLS_MANIFEST_BAD_TOTAL_LENGTH = 11,
    HFOC_MBEDTLS_MANIFEST_TRAILING_BYTES = 12,
    HFOC_MBEDTLS_MANIFEST_BAD_DIGEST = 13,
    HFOC_MBEDTLS_MANIFEST_CERTIFICATE_PARSE_FAILED = 14,
    HFOC_MBEDTLS_MANIFEST_CERTIFICATE_CHAIN_REJECTED = 15,
    HFOC_MBEDTLS_MANIFEST_CERTIFICATE_NOT_EC = 16,
    HFOC_MBEDTLS_MANIFEST_CERTIFICATE_NOT_P256 = 17,
    HFOC_MBEDTLS_MANIFEST_CERTIFICATE_HOSTNAME_MISMATCH = 18,
    HFOC_MBEDTLS_MANIFEST_KEY_PARSE_FAILED = 19,
    HFOC_MBEDTLS_MANIFEST_KEY_NOT_EC = 20,
    HFOC_MBEDTLS_MANIFEST_KEY_NOT_P256 = 21,
    HFOC_MBEDTLS_MANIFEST_KEY_MISMATCH = 22,
    HFOC_MBEDTLS_MANIFEST_LAST_STATUS =
        HFOC_MBEDTLS_MANIFEST_KEY_MISMATCH,
};

enum hfoc_mbedtls_manifest_status hfoc_mbedtls_manifest_parse(
    struct hfoc_mbedtls_manifest *manifest,
    const void *manifest_bytes,
    uint32_t manifest_length);
const char *hfoc_mbedtls_manifest_status_string(
    enum hfoc_mbedtls_manifest_status status);

#endif

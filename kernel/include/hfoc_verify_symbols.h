/*
 * ITEM-386 verification-profile symbol namespace.
 *
 * The production image carries two mbedTLS profiles at once: the frozen
 * ITEM-372 verification profile (image_signature_ecdsa.c and the bounded
 * arithmetic it links) and the ITEM-386 TLS-serving profile.  Both profiles
 * compile the same mbedTLS translation units, but with different allocator
 * hooks, so the two object sets export the same symbols and cannot be linked
 * together unchanged.  Sharing them is what broke the TLS 1.3 handshake: the
 * TLS path resolved the big-integer, elliptic-curve and message-digest entry
 * points to the verification objects, so a connection was built from the
 * verification arena and released through the TLS pools.
 *
 * Every link-visible symbol the verification closure exports is therefore
 * moved into its own namespace here.  The rename is installed from
 * hfoc_verify_config.h, before any mbedTLS header is parsed, so declarations
 * and definitions agree inside the profile and the verification path refers
 * to the renamed names.  The TLS closure keeps the plain mbedTLS names.
 *
 * This is a link-time namespace split only: no algorithm, allocator hook,
 * error code or buffer bound changes, so the verification path stays
 * byte-for-byte the path the ITEM-372 proofs measured.  The list is checked
 * against the built objects by scripts/verify-mbedtls-object-partition.sh,
 * which fails if a verification translation unit ever exports a symbol that
 * is missing here.
 */

